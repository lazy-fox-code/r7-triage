function merge(defaults, stored) {
  const out = {};
  for (const [k, v] of Object.entries(defaults)) {
    const s = stored?.[k];
    if (v && typeof v === "object" && !Array.isArray(v)) {
      out[k] = merge(v, s);
    } else {
      out[k] = s === undefined ? v : s;
    }
  }
  return out;
}

export async function load() {
  const stored = await browser.storage.local.get(null);
  return merge(DEFAULTS, stored);
}

/** Сохраняет ветку настроек целиком: `save("scan", {...})`. */
export async function save(section, value) {
  const current = await load();
  const next = merge(DEFAULTS[section] ?? {}, { ...current[section], ...value });
  await browser.storage.local.set({ [section]: next });
  return next;
}
