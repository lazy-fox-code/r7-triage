// Единственное место, где живут значения по умолчанию. В коде прохода и
// классификации числовых констант быть не должно: адрес модели, её имя и
// пороги задаются пользователем.
//
// Здесь — `browser.storage.local`, и это осознанно: настроек десятки байт,
// читаются они редко. В IndexedDB уходит то, чего тут быть не может, —
// письма, вердикты и курсоры прохода.

export const DEFAULTS = {
  // Модель. Пустой эндпоинт означает «не настроено»: проход по ящику (T1)
  // модель не зовёт вовсе, так что пустое значение — рабочее состояние.
  llm: {
    endpoint: "",
    model: "",
    concurrency: 3,
    bodyLimit: 4000,
    timeoutMs: 60000,
  },

  scan: {
    // Специальные папки, которые не разбираем. `type` у MailFolder в TB 115
    // заполнен только для служебных папок, у обычных он отсутствует.
    excludeFolderTypes: ["trash", "junk", "templates"],

    // Граница между свежим и архивным проходом. Свежий проход разбирает
    // последние столько суток при старте клиента и на приход новой почты;
    // всё, что старше, достаётся архивному проходу в простое.
    recentDays: 30,

    // Разбирать архивы в простое. Выключить — и архив будет разбираться
    // только по явной команде из панели.
    archiveOnIdle: true,
    // Через сколько секунд бездействия считать, что пользователь отошёл.
    idleSeconds: 60,
    // Как часто пересматривать уже разобранный архив. За это время успевает
    // состариться свежая почта, и её надо подобрать архивным проходом.
    archiveRecheckDays: 7,

    // Разбор папки идёт окнами по дате, от свежих писем к старым. Размер
    // окна подстраивается под плотность переписки: цель — держать окно
    // близко к targetPerWindow писем.
    initialWindowDays: 30,
    minWindowDays: 7,
    maxWindowDays: 3650,
    targetPerWindow: 2000,

    // Соседние окна перекрываются, чтобы письмо, попавшее ровно на границу,
    // не потерялось между ними. Подробности — в scan.js.
    overlapDays: 1,

    // Нижняя граница поиска по дате. Всё, что старше, забирается одним
    // финальным запросом без нижней границы.
    floorYear: 1990,

    // Пауза между страницами. Ноль для фонового прохода нормален: вызовы
    // асинхронные и цикл событий не блокируют. Поднять, если клиент
    // ощутимо тормозит во время разбора.
    throttleMs: 0,

    // Продолжать незавершённый проход при следующем запуске клиента.
    autoResume: true,
  },
};

function merge(defaults, stored) {
  const out = {};
  for (const [k, v] of Object.entries(defaults)) {
    const s = stored?.[k];
    if (v && typeof v === "object" && !Array.isArray(v)) {
      out[k] = merge(v, s);
    } else {
      out[k] = s === undefined ? v : s;
    }
  }
  return out;
}

export async function load() {
  const stored = await browser.storage.local.get(null);
  return merge(DEFAULTS, stored);
}

/** Сохраняет ветку настроек целиком: `save("scan", {...})`. */
export async function save(section, value) {
  const current = await load();
  const next = merge(DEFAULTS[section] ?? {}, { ...current[section], ...value });
  await browser.storage.local.set({ [section]: next });
  return next;
}
