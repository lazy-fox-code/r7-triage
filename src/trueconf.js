// TrueConf со стороны почты.
//
// Сейчас здесь только распознавание ссылок на конференции в письмах и
// приглашениях. Сервер TrueConf — второй разрешённый сетевой адресат, но
// только под учётной записью пользователя; клиент API с авторизацией от
// его имени — trueconf-api.js.
//
// Зачем ссылки уже сейчас. Приглашение в календаре, письмо «подключайтесь
// по ссылке» и запись о конференции в TrueConf Server API называют одну и ту
// же конференцию. Проход обогащения читает письмо целиком один раз, и
// извлечь ключ дешевле тогда, чем перечитывать ящик, когда появится доступ к
// API. С доступом участники и фактическое время конференции присоединятся к
// делу по этому ключу.
//
// Ключ — номер вместе с темой. Номера конференций на сервере время от
// времени обнуляют, и один номер в разные месяцы означает разные
// конференции. Номер без темы склеил бы в одно дело планёрку отдела и
// совещание по договору, получившие один номер в разное время. У API в
// записи конференции тоже есть `id` и `topic`, так что ключ совпадёт с обеих
// сторон. Тема берётся из приглашения (SUMMARY встречи), а если ссылка
// встретилась в обычном письме — из темы письма.
//
// Форматы ссылок сверить на живых приглашениях своего сервера:
//   https://<сервер>/c/<id>     страница конференции
//   trueconf:c/<id>@<сервер>    запуск клиента; разделители встречаются
//                               разные, разбор к ним терпим

import { normalizeSubject } from "./keys.js";

// Идентификатор конференции: буквы, цифры, «_», «.», «-». Точку и дефис в
// конце отрезаем — это конец предложения, а не часть идентификатора.
const ID = "[A-Za-z0-9_.-]+";
const HTTP = new RegExp(`\\bhttps?://([a-z0-9.-]+)(?::\\d+)?/c/(${ID})`, "gi");
const SCHEME = new RegExp(`\\btrueconf:[\\\\/]{0,2}c[\\\\/]+(${ID})(?:@([a-z0-9.-]+))?`, "gi");

const trimId = (id) => id.replace(/[.-]+$/, "");

/**
 * Ссылки на конференции TrueConf в тексте.
 *
 * Ссылки вида https://…/c/… признаются только на серверах из настроек:
 * путь /c/ слишком общий, чтобы узнавать TrueConf по нему одному.
 *
 * @param {string} text
 * @param {string[]} hosts имена серверов TrueConf из настроек
 * @returns {{ host: string|null, id: string }[]}
 */
export function conferenceRefs(text, hosts = []) {
  if (!text) return [];
  const known = new Set(hosts.map((h) => String(h).trim().toLowerCase()).filter(Boolean));
  const out = new Map();
  const add = (host, id) => {
    const clean = trimId(id);
    if (!clean) return;
    const h = host ? host.toLowerCase() : null;
    out.set(`${h ?? ""}|${clean}`, { host: h, id: clean });
  };

  if (known.size) {
    for (const m of String(text).matchAll(HTTP)) {
      if (known.has(m[1].toLowerCase())) add(m[1], m[2]);
    }
  }
  for (const m of String(text).matchAll(SCHEME)) add(m[2] ?? null, m[1]);

  return [...out.values()];
}

/**
 * Ключ конференции: сервер, номер и тема. Тема нормализуется так же, как
 * тема письма, — «Приглашение: Планёрка» и «Планёрка» дают один ключ.
 *
 * @param {{ host: string|null, id: string }} ref
 * @param {string} topic
 */
export function conferenceKey(ref, topic) {
  return `tc:${ref.host ?? ""}|${ref.id}|${normalizeSubject(topic)}`;
}
